#!/usr/bin/env python3
"""Generate per-tool packaging from the single source of truth: .claude/skills/*/SKILL.md.

Usage:
  python3 scripts/build-targets.py          # (re)write all generated files
  python3 scripts/build-targets.py --check  # exit 1 if any generated file is missing or stale (CI)

Stdlib only. Formats chosen from each tool's current docs (checked 2026-10-16):
  Claude Code  .claude-plugin/plugin.json, marketplace.json  https://code.claude.com/docs/en/plugins-reference
                                                            https://code.claude.com/docs/en/plugin-marketplaces
  Gemini CLI   gemini-extension.json + GEMINI.md + skills/   https://geminicli.com/docs/extensions/reference/
  Cursor       reads .claude/skills natively; .cursor/rules/*.mdc (alwaysApply)
                                                            https://cursor.com/docs/skills  https://cursor.com/docs/rules
  Grok         reads Claude Code plugins/marketplaces/skills and AGENTS.md natively
                                                            https://docs.x.ai/build/features/skills-plugins-marketplaces
  Codex CLI    AGENTS.md; skills from .agents/skills or ~/.agents/skills (install copies skills/)
                                                            https://learn.chatgpt.com/docs/build-skills.md
  Copilot      .github/copilot-instructions.md; reads .claude/skills natively
                                                            https://docs.github.com/en/copilot/concepts/agents/about-agent-skills
"""
import json, os, re, shutil, sys, filecmp

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, ".claude", "skills")
PACK = {
    "name": "sre",
    "displayName": "SRE skill pack",
    "version": "3.1.0",  # single source of truth for the pack version
    "description": "Generic SRE skills with shared approval gates: incident command, diagnosis, database triage (Postgres, MySQL, Redis), certificate and domain expiry audits, gated remediation, SLOs, DR, capacity, cost, and read-only adapters for Kubernetes, AWS, Azure, GCP, Terraform, Dynatrace, Prometheus/Grafana, Datadog and PagerDuty/Opsgenie.",
    "author": {"name": "Mike May", "email": "mike48229@gmail.com"},
    "repository": "https://github.com/kryptophonik/claude-sre",
    "license": "MIT",
    "keywords": ["sre", "incident-response", "kubernetes", "observability", "on-call", "slo"],
}
HEADER = "GENERATED by scripts/build-targets.py from .claude/skills/*/SKILL.md. Do not edit; edit the skills and re-run."


def skills():
    out = []
    for name in sorted(os.listdir(SRC)):
        p = os.path.join(SRC, name, "SKILL.md")
        if not os.path.isfile(p):
            continue
        s = open(p, encoding="utf-8").read()
        m = re.match(r"---\n(.*?)\n---\n", s, re.S)
        fm = {}
        for line in m.group(1).splitlines():
            k, _, v = line.partition(":")
            v = v.strip()
            if v.startswith('"'):
                v = json.loads(v)
            fm[k.strip()] = v
        out.append({"name": fm["name"], "description": fm.get("description", ""),
                    "manual": fm.get("disable-model-invocation") == "true",
                    "reference": fm.get("user-invocable") == "false"})
    return out


def gate_block():
    s = open(os.path.join(SRC, "sre-safety-gates", "SKILL.md"), encoding="utf-8").read()
    m = re.search(r"## The gates\n\n(.*?)(?=\n## )", s, re.S)
    return m.group(1).strip()


def index_table(sk, link_prefix):
    rows = ["| Skill | Use when | Invocation |", "|---|---|---|"]
    for k in sk:
        inv = "manual only" if k["manual"] else ("reference (loaded by other skills)" if k["reference"] else "auto")
        rows.append(f"| [`{k['name']}`]({link_prefix}{k['name']}/SKILL.md) | {k['description'].replace('|', '/')} | {inv} |")
    return "\n".join(rows)


PATHS_NOTE = """
Script and reference paths inside a skill (for example `scripts/az-ro.sh` or `../sre-k8s-triage/scripts/...`) are relative to that skill's folder, the folder containing its `SKILL.md`. Resolve them against that folder: `cd` into it, or prefix the skill path. Older copies may write `${CLAUDE_SKILL_DIR}`, which means the same folder; substitute it yourself if your tool doesn't.
"""


def instructions(sk, title, link_prefix, extra=""):
    return f"""<!-- {HEADER} -->
# {title}

This repository is a generic SRE skill pack. Each skill is a folder with a `SKILL.md` (Agent Skills format). Load the matching skill before acting.

## Safety gates (always apply, for every skill and every tool)

{gate_block()}

Never run a write command, call an MCP write tool, or post an external message without explicit human approval in this conversation. Skills marked "manual only" must be started by the user (for example `/sre-chaos-engineering`, or `/sre:sre-chaos-engineering` in a Claude Code plugin install); never run their steps on your own.
{PATHS_NOTE}
{extra}
## Skills

{index_table(sk, link_prefix)}
"""


def render(sk):
    files = {}
    files[".claude-plugin/plugin.json"] = json.dumps({
        **{k: PACK[k] for k in ("name", "displayName", "version", "description", "author", "repository", "license", "keywords")},
    }, indent=2) + "\n"
    files[".claude-plugin/marketplace.json"] = json.dumps({
        "name": "claude-sre",
        "description": "SRE skill pack with shared approval gates",
        "owner": PACK["author"],
        "plugins": [{"name": PACK["name"], "source": "./", "description": PACK["description"], "version": PACK["version"]}],
    }, indent=2) + "\n"
    files["gemini-extension.json"] = json.dumps({
        "name": PACK["name"], "version": PACK["version"], "description": PACK["description"],
        "contextFileName": "GEMINI.md",
    }, indent=2) + "\n"
    files["GEMINI.md"] = instructions(sk, "SRE skill pack (Gemini CLI context)", "skills/")
    files["AGENTS.md"] = instructions(sk, "SRE skill pack (AGENTS.md: Codex, Cursor, Grok, Copilot)", ".claude/skills/",
        "\nSkills live in `.claude/skills/` (read natively by Claude Code, Cursor, Copilot and Grok). Codex reads `.agents/skills/`: install per docs/install/codex.md.\n")
    files[".github/copilot-instructions.md"] = instructions(sk, "SRE skill pack (GitHub Copilot)", "../.claude/skills/")
    files[".cursor/rules/sre-safety-gates.mdc"] = (
        "---\ndescription: SRE pack safety gates (always on)\nalwaysApply: true\n---\n\n"
        f"<!-- {HEADER} -->\n\n# SRE safety gates\n\n{gate_block()}\n\n"
        "Never run a write command, call an MCP write tool, or post an external message without explicit human approval. "
        "Skills live in `.claude/skills/` (Cursor reads them natively); manual-only skills must be started by the user with `/<skill-name>`.\n")
    # Codex: agents/openai.yaml blocks implicit invocation for manual-only skills
    # (https://learn.chatgpt.com/docs/build-skills.md, "Optional metadata").
    for k in sk:
        if k["manual"]:
            files[f".claude/skills/{k['name']}/agents/openai.yaml"] = (
                f"# {HEADER}\n# Codex: manual only (mirrors disable-model-invocation: true). Start with ${k['name']}.\n"
                "policy:\n  allow_implicit_invocation: false\n")
    return files


def mirror_plan():
    """skills/ is a byte-for-byte mirror of .claude/skills for plugin/extension installs (Claude plugin, Gemini extension, gh skill, Codex copy)."""
    plan = {}
    for d, _, fs in os.walk(SRC):
        if "__pycache__" in d:
            continue
        for f in fs:
            src = os.path.join(d, f)
            rel = os.path.relpath(src, SRC)
            plan[os.path.join("skills", rel)] = src
    return plan


def main():
    check = "--check" in sys.argv
    sk = skills()
    files = render(sk)
    files["skills/README.md"] = f"# skills/ (generated mirror)\n\n{HEADER}\n\nThis folder exists for plugin and extension installs (Claude Code plugin, Gemini CLI extension, `gh skill install`, Codex). The source of truth is `.claude/skills/`.\n"
    stale = []
    for rel, content in files.items():
        p = os.path.join(ROOT, rel)
        cur = open(p, encoding="utf-8").read() if os.path.exists(p) else None
        if cur != content:
            stale.append(rel)
            if not check:
                os.makedirs(os.path.dirname(p), exist_ok=True)
                open(p, "w", encoding="utf-8").write(content)
    plan = mirror_plan()
    for rel, src in plan.items():
        dst = os.path.join(ROOT, rel)
        if not os.path.exists(dst) or not filecmp.cmp(src, dst, shallow=False) or (os.stat(src).st_mode & 0o111) != (os.stat(dst).st_mode & 0o111):
            stale.append(rel)
            if not check:
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                shutil.copy2(src, dst)
    keep = set(plan) | {"skills/README.md"}
    for d, _, fs in os.walk(os.path.join(ROOT, "skills")):
        for f in fs:
            rel = os.path.relpath(os.path.join(d, f), ROOT)
            if rel not in keep:
                stale.append(rel + " (orphan)")
                if not check:
                    os.remove(os.path.join(ROOT, rel))
    if check:
        if stale:
            print("Generated outputs are stale. Run: python3 scripts/build-targets.py\n  " + "\n  ".join(stale[:50]))
            sys.exit(1)
        print(f"generated outputs up to date ({len(sk)} skills)")
    else:
        print(f"wrote {len(stale)} file(s); {len(sk)} skills")


if __name__ == "__main__":
    main()
