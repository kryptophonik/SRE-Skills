#!/usr/bin/env python3
"""Generate Prometheus multiwindow, multi-burn-rate SLO rules (recording + alerting).

Implements the four-tier scheme from the Google SRE Workbook, ch. 5 "Alerting on SLOs",
approach 6, Table 5-8 (https://sre.google/workbook/alerting-on-slos/, fetched 2026-10-16):

  severity  long  short  budget consumed  burn rate (30d period)
  page      1h    5m     2%               14.4
  page      6h    30m    5%               6
  ticket    1d    2h     10%              3
  ticket    3d    6h     10%              1

Burn rate = budget_fraction * period / long_window, so a period other than 30d (e.g. 28d)
rescales the factors while keeping the same budget fractions.

Output follows the Prometheus rule-file format
(https://prometheus.io/docs/prometheus/latest/configuration/recording_rules/, Prometheus 3.x)
and recording-rule naming level:metric:operations
(https://prometheus.io/docs/practices/rules/). Validate with:
  promtool check rules --lint=all --lint-fatal <file>
  promtool test rules <test-file>

Stdlib only; no network, no writes except --out.
"""
import argparse
import re
import sys
from decimal import Decimal, InvalidOperation

TIERS = [  # (severity, long, short, budget_fraction)
    ("page", "1h", "5m", Decimal("0.02")),
    ("page", "6h", "30m", Decimal("0.05")),
    ("ticket", "1d", "2h", Decimal("0.10")),
    ("ticket", "3d", "6h", Decimal("0.10")),
]
WINDOWS = ["5m", "30m", "1h", "2h", "6h", "1d", "3d"]
UNIT_H = {"m": Decimal(1) / 60, "h": Decimal(1), "d": Decimal(24), "w": Decimal(168)}
LABEL_RE = re.compile(r"^[a-zA-Z_][a-zA-Z0-9_]*$")


def hours(d):
    m = re.fullmatch(r"(\d+)([mhdw])", d)
    if not m:
        raise ValueError(f"bad duration {d!r} (use e.g. 30d, 28d, 4w)")
    return Decimal(m.group(1)) * UNIT_H[m.group(2)]


def fmt(d):
    s = format(d.normalize(), "f")
    return s if "." in s or "e" in s.lower() else s


def q(s):
    """YAML double-quoted scalar."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def check_selector(name, sel):
    if sel.count("{") != sel.count("}") or sel.count("(") != sel.count(")"):
        raise ValueError(f"{name}: unbalanced braces/parentheses in {sel!r}")
    if "[" in sel:
        raise ValueError(f"{name}: pass a bare selector, without a range; the generator adds [window]")


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--slo-name", required=True, help='value of the "slo" label, e.g. checkout-availability')
    p.add_argument("--objective", required=True, help="SLO target as a ratio, e.g. 0.999")
    p.add_argument("--errors", required=True, help='bad-events counter selector, e.g. \'http_requests_total{job="<svc>",code=~"5.."}\'')
    p.add_argument("--total", required=True, help='all-events counter selector, e.g. \'http_requests_total{job="<svc>"}\'')
    p.add_argument("--by", default="job", help="comma-separated labels to keep (default: job; empty string = none)")
    p.add_argument("--period", default="30d", help="SLO period used to derive burn rates (default 30d)")
    p.add_argument("--for", dest="for_", default="", help="optional 'for:' on alerts; SRE Workbook recommends none (default: omitted)")
    p.add_argument("--runbook-url", default="https://runbooks.example.com/slo/<slo-name>", help="runbook_url annotation")
    p.add_argument("--interval", default="", help="optional rule-group evaluation interval, e.g. 1m")
    p.add_argument("--out", default="-", help="output file (default stdout)")
    a = p.parse_args(argv)

    try:
        obj = Decimal(a.objective)
    except InvalidOperation:
        p.error("--objective must be a number such as 0.999")
    if not (Decimal(0) < obj < Decimal(1)):
        p.error("--objective must be strictly between 0 and 1 (e.g. 0.999, not 99.9)")
    if not re.fullmatch(r"[A-Za-z0-9._-]+", a.slo_name):
        p.error("--slo-name may contain only letters, digits, '.', '_' and '-'")
    by = [b.strip() for b in a.by.split(",") if b.strip()]
    for b in by:
        if not LABEL_RE.match(b):
            p.error(f"--by: invalid label name {b!r}")
    if "slo" in by:
        p.error('--by must not contain "slo" (it is added by the generator)')
    try:
        check_selector("--errors", a.errors)
        check_selector("--total", a.total)
        period_h = hours(a.period)
        if a.for_:
            hours(a.for_)
        if a.interval:
            hours(a.interval)
    except ValueError as e:
        p.error(str(e))

    budget = Decimal(1) - obj
    agg = f"sum by ({', '.join(by)})" if by else "sum"
    runbook = a.runbook_url.replace("<slo-name>", a.slo_name)
    sel = f'{{slo="{a.slo_name}"}}'

    out = []
    w = out.append
    w(f"# Generated by gen-burn-rate-rules.py: SLO {a.slo_name}, objective {fmt(obj)}, period {a.period}.")
    w("# Multiwindow multi-burn-rate rules per https://sre.google/workbook/alerting-on-slos/ (Table 5-8).")
    w("# Rule format: https://prometheus.io/docs/prometheus/latest/configuration/recording_rules/ (Prometheus 3.x).")
    w("# Verified 2026-10-16 with promtool 3.15.0. Validate: promtool check rules --lint=all --lint-fatal <this file>")
    w("groups:")
    w(f"  - name: slo-{a.slo_name}")
    if a.interval:
        w(f"    interval: {a.interval}")
    w("    rules:")
    for win in WINDOWS:
        expr = f"{agg} (rate({a.errors}[{win}]))\n/\n{agg} (rate({a.total}[{win}]))"
        w(f"      - record: slo:sli_error:ratio_rate{win}")
        w("        expr: |")
        for line in expr.split("\n"):
            w(f"          {line}")
        w("        labels:")
        w(f"          slo: {q(a.slo_name)}")

    factors = []
    for sev, lw, sw, frac in TIERS:
        f = (frac * period_h / hours(lw)).quantize(Decimal("0.0001")).normalize()
        factors.append((sev, lw, sw, frac, f))
        if f * budget >= 1:
            print(f"warning: {lw}/{sw} tier needs error ratio {fmt(f * budget)} >= 1 and can never fire "
                  f"(objective too low for this tier; see SRE Workbook 'Extreme Availability Goals')", file=sys.stderr)

    for sev in ("page", "ticket"):
        parts = []
        for s, lw, sw, frac, f in factors:
            if s != sev:
                continue
            thr = f"({fmt(f)} * {fmt(budget)})"
            parts.append(
                f"(\n  slo:sli_error:ratio_rate{lw}{sel} > {thr}\nand\n  slo:sli_error:ratio_rate{sw}{sel} > {thr}\n)")
        name = "SLOErrorBudgetBurnFast" if sev == "page" else "SLOErrorBudgetBurnSlow"
        tiers = ", ".join(f"{fmt(f)}x over {lw}/{sw}" for s, lw, sw, _, f in factors if s == sev)
        w(f"      - alert: {name}")
        w("        expr: |")
        for line in "\nor\n".join(parts).split("\n"):
            w(f"          {line}")
        if a.for_:
            w(f"        for: {a.for_}")
        w("        labels:")
        w(f"          severity: {sev}")
        w(f"          slo: {q(a.slo_name)}")
        w("        annotations:")
        w(f"          summary: {q('SLO ' + a.slo_name + ' error budget burn (' + sev + ')')}")
        w(f"          description: {q('Error ratio is above the burn-rate threshold (' + tiers + '; objective ' + fmt(obj) + ', period ' + a.period + '). Long-window error ratio of the first matching tier: {{ $value | humanizePercentage }}.')}")
        w(f"          runbook_url: {q(runbook)}")

    text = "\n".join(out) + "\n"
    if a.out == "-":
        sys.stdout.write(text)
    else:
        with open(a.out, "w") as fh:
            fh.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
